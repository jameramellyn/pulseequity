// Browser check of UI state handling with a MOCKED /api/analyze (no Claude calls, no cost).
// Requires Google Chrome installed and the app running: `npm run build && npm start`, then `npm run test:ui`.
import { chromium } from "playwright-core";
const URL = process.env.PE_URL ?? "http://localhost:3000/";
const SHOTS = process.env.PE_SHOTS ?? "/tmp";
const results = [];
const check = (name, ok, extra = "") => { results.push({ name, ok }); console.log(`${ok ? "PASS" : "FAIL"}  ${name}${extra ? "  — " + extra : ""}`); };
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

const browser = await chromium.launch({ channel: "chrome", headless: true });
const page = await (await browser.newContext({ viewport: { width: 1280, height: 1000 } })).newPage();
const consoleErrors = [];
page.on("console", (m) => m.type() === "error" && consoleErrors.push(m.text()));
page.on("pageerror", (e) => consoleErrors.push(String(e)));

// ---- Mocked /api/analyze (no live Claude): behaviour chosen by age in the intake.
let liveCalls = 0;
const mockResult = (summary) => ({
  concernLevel: "possible_concern", summary, detectedMarkers: [], potentialDismissalPattern: null,
  recommendedAction: "Clinician review under local protocol.", limitations: [],
});
let errorMode = null;
await page.route("**/api/analyze", async (route) => {
  liveCalls++;
  const body = JSON.parse(route.request().postData());
  const age = body.intake.age;
  const delay = age === 58 ? 1500 : 100; // Case A slow, others fast
  await sleep(delay);
  let payload, status = 200;
  if (errorMode) { status = 429; payload = { success: false, requestId: body.requestId, error: { code: errorMode, message: "Mock rate limit", retryable: true } }; }
  else if (age === 58 && globalThis.lateError) { status = 503; payload = { success: false, requestId: body.requestId, error: { code: "UPSTREAM_ERROR", message: "LATE-ERROR-A", retryable: true } }; }
  else payload = { success: true, requestId: body.requestId, source: "live", data: mockResult(`MOCK-AGE-${age}`) };
  try { await route.fulfill({ status, contentType: "application/json", body: JSON.stringify(payload) }); } catch {}
});

const dash = () => page.locator("section[aria-labelledby=dashboard-heading]").innerText();
const caseBtn = (letter) => page.getByRole("button", { name: new RegExp(`Case ${letter}`) });
await page.goto(URL);
await page.getByText("Synthetic demo · not clinical software").waitFor();
check("header shows persistent synthetic-demo label", true);

// ---- Fixture mode
await page.getByLabel("Prewritten demo (no AI call)").check();
await caseBtn("A").click();
let d = await dash();
check("fixture A shows exact prewritten label", d.includes("Prewritten demo response — not generated by live Claude.") && d.includes("Case A"));
check("fixture A shows elevated category + action", d.includes("Elevated concern") && /recommended next step/i.test(d) && !d.includes("\"\""));
await page.screenshot({ path: `${SHOTS}/1-fixture-A.png`, fullPage: true });
await caseBtn("C").click();
d = await dash();
check("fixture C shows neutral no-markers text with disclaimer", d.includes("No specific markers identified by this prototype") && d.includes("does not rule out cardiac disease") && d.includes("Case C"));
check("fixture C lists not-recorded inputs", d.includes("Not recorded in intake: Systolic BP, Diastolic BP"));
await page.screenshot({ path: `${SHOTS}/2-fixture-C.png`, fullPage: true });
await page.getByLabel(/Heart rate/).fill("79");
d = await dash();
check("editing a fixture removes its canned response", !d.includes("Prewritten demo response") && d.includes("prewritten response removed"));
check("no live call made in fixture mode", liveCalls === 0, `liveCalls=${liveCalls}`);

// ---- Mode switch clears result
await caseBtn("B").click();
await page.getByLabel("Live AI (Claude via server)").check();
d = await dash();
check("switching mode clears the fixture result", !d.includes("Prewritten demo response") && d.includes("Mode changed") === false && d.includes("Live AI mode"));

// ---- Live: rapid case switch (A slow, B fast)
await caseBtn("A").click();
await caseBtn("B").click();
await sleep(2200);
d = await dash();
check("rapid case switch shows only latest (B) result", d.includes("MOCK-AGE-64") && !d.includes("MOCK-AGE-58"));
check("live result labelled as live Claude response", d.includes("Live Claude response"));

// ---- Late error from old request cannot clear newer success
globalThis.lateError = true;
await caseBtn("A").click();
await caseBtn("C").click();
await sleep(2200);
d = await dash();
check("late error from superseded request cannot clear newer success", d.includes("MOCK-AGE-41") && !d.includes("LATE-ERROR-A"));
globalThis.lateError = false;

// ---- Edit during loading
await caseBtn("A").click();
await page.getByText("Analyzing with live Claude").waitFor();
await page.getByLabel(/Chief complaint/).fill("Edited while loading: jaw ache");
await sleep(2000);
d = await dash();
check("edit during loading: old result never appears", !d.includes("MOCK-AGE-58") && d.includes("Input changed"));

// ---- Mode switch during loading
await caseBtn("A").click();
await page.getByLabel("Prewritten demo (no AI call)").check();
await sleep(2000);
d = await dash();
check("mode switch during loading: old live result never appears", !d.includes("MOCK-AGE-58"));
await page.getByLabel("Live AI (Claude via server)").check();

// ---- Reset during loading
await caseBtn("A").click();
await page.getByRole("button", { name: "Reset form" }).click();
await sleep(2000);
d = await dash();
const ageVal = await page.getByLabel(/Age \(years\)/).inputValue();
const diab = await page.getByLabel("Diabetes").inputValue();
check("reset during loading clears form (unknowns restored) and shows no result", !d.includes("MOCK-AGE-58") && ageVal === "" && diab === "unknown");

// ---- Validation
await page.getByRole("button", { name: "Run cardiac check" }).click();
const formText = await page.locator("form").innerText();
check("blank submit shows field errors without calling server", formText.includes("Age is required.") && formText.includes("Chief complaint must be"));
await page.screenshot({ path: `${SHOTS}/3-validation.png`, fullPage: true });

// ---- Error state + retry
errorMode = "RATE_LIMITED";
await caseBtn("B").click();
await page.getByText("Analysis unavailable").waitFor();
d = await dash();
check("service error shown honestly with retry, no fixture substituted", d.includes("RATE_LIMITED") && d.includes("Nothing was substituted") && !d.includes("Prewritten"));
await page.screenshot({ path: `${SHOTS}/4-error.png`, fullPage: true });
errorMode = null;
await page.getByRole("button", { name: "Retry" }).click();
await page.getByText("MOCK-AGE-64").waitFor({ timeout: 3000 });
check("retry resubmits and shows new result", true);

// ---- Keyboard-only path: pick fixture mode and Case A via keyboard
await page.reload();
await page.locator("body").focus();
let found = false;
for (let i = 0; i < 25; i++) {
  await page.keyboard.press("Tab");
  const label = await page.evaluate(() => document.activeElement?.getAttribute("value") ?? document.activeElement?.textContent ?? "");
  if (label === "live") { await page.keyboard.press("ArrowRight"); found = true; break; }
}
const modeIsFixture = await page.getByLabel("Prewritten demo (no AI call)").isChecked();
let reachedCase = false;
for (let i = 0; i < 10 && found; i++) {
  await page.keyboard.press("Tab");
  const txt = await page.evaluate(() => document.activeElement?.textContent ?? "");
  if (txt.includes("Case A")) { await page.keyboard.press("Enter"); reachedCase = true; break; }
}
d = await dash();
check("keyboard: arrow-select mode, Tab to case, Enter shows fixture", modeIsFixture && reachedCase && d.includes("Prewritten demo response"));
await page.screenshot({ path: `${SHOTS}/5-keyboard.png`, fullPage: true });

// ---- Raw HTML not rendered
const injected = await page.evaluate(() => document.querySelectorAll("section script, section img[onerror]").length);
check("no injected HTML elements in dashboard", injected === 0);

const unexpected = consoleErrors.filter((e) => !e.includes("status of 429"));
check("no unexpected browser console errors (mocked 429 excluded)", unexpected.length === 0, unexpected.slice(0, 3).join(" | "));
await browser.close();
const failed = results.filter((r) => !r.ok).length;
console.log(`\n${results.length - failed}/${results.length} checks passed`);
process.exit(failed ? 1 : 0);
