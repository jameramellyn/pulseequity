import { readFileSync } from "node:fs";
import { describe, expect, it } from "vitest";
import { BP_ORDER_MESSAGE, OUT_OF_RANGE_MESSAGE, softWarnings } from "@/lib/entry-ranges";
import { SYNTHETIC_CASES } from "@/lib/fixtures";
import { emptyFormValues, formToIntake, intakeToForm } from "@/lib/intake-form";
import { REFERENCE_INVENTORY_VERSION } from "@/lib/references";
import { buildSummaryText, sourceLabel } from "@/lib/summary";
import { APP_VERSION } from "@/lib/version";

describe("soft entry-range warnings (typo hints only)", () => {
  const base = { ...emptyFormValues(), age: "50", chiefComplaint: "tired" };

  it("flags implausible entries without blocking submission", () => {
    const values = { ...base, heartRate: "960" };
    expect(softWarnings(values).heartRate).toBe(OUT_OF_RANGE_MESSAGE);
    expect(formToIntake(values).ok).toBe(true); // still submittable, value unchanged
  });

  it("is silent for blanks, typical entries, and format errors", () => {
    expect(softWarnings(base)).toEqual({});
    expect(softWarnings({ ...base, heartRate: "96", systolicBP: "148", diastolicBP: "90", respiratoryRate: "18" })).toEqual({});
    expect(softWarnings({ ...base, heartRate: "abc" })).toEqual({});
  });

  it("hints at swapped blood pressure entries", () => {
    expect(softWarnings({ ...base, systolicBP: "80", diastolicBP: "120" }).diastolicBP).toBe(BP_ORDER_MESSAGE);
  });

  it("never produces clinical High/Low language", () => {
    const all = softWarnings({ ...base, heartRate: "5", systolicBP: "400", diastolicBP: "500", respiratoryRate: "100" });
    for (const msg of Object.values(all)) expect(msg).not.toMatch(/\b(high|low|abnormal|tachy|brady|hypo|hyper)/i);
  });
});

describe("copy summary text", () => {
  const c = SYNTHETIC_CASES[0];
  const text = buildSummaryText(c.prewrittenResult, { source: "fixture", missing: ["Respiratory rate"] });

  it("contains category, summary, next step, findings, limitations, disclaimer and versions", () => {
    expect(text).toContain("Category: Elevated concern");
    expect(text).toContain(c.prewrittenResult.summary);
    expect(text).toContain(`Recommended next step: ${c.prewrittenResult.recommendedAction}`);
    expect(text).toContain("Back discomfort");
    expect(text).toContain("Source: AHA");
    expect(text).toContain(c.prewrittenResult.limitations[0]);
    expect(text).toContain("Not recorded in intake: Respiratory rate.");
    expect(text).toContain("SYNTHETIC DEMO");
    expect(text).toContain("Prewritten demo response — not generated by live Claude.");
    expect(text).toContain(`App version ${APP_VERSION}`);
    expect(text).toContain(`Reference inventory ${REFERENCE_INVENTORY_VERSION}`);
  });

  it("keeps the no-markers disclaimer and never says all clear", () => {
    const none = buildSummaryText(SYNTHETIC_CASES[2].prewrittenResult, { source: "live", missing: [] });
    expect(none).toContain("does not rule out cardiac disease");
    expect(none).not.toMatch(/all clear|cleared|non-urgent/i);
  });

  it("maps source IDs to readable names", () => {
    expect(sourceLabel("AHA_SYMPTOMS_WOMEN")).toBe("AHA");
    expect(sourceLabel("UNKNOWN_ID")).toBe("UNKNOWN_ID");
  });
});

describe("version metadata", () => {
  it("APP_VERSION matches package.json", () => {
    const pkg = JSON.parse(readFileSync(new URL("../package.json", import.meta.url), "utf8"));
    expect(APP_VERSION).toBe(pkg.version);
  });

  it("fixture round-trip still holds (presentation change did not touch contracts)", () => {
    for (const s of SYNTHETIC_CASES) expect(formToIntake(intakeToForm(s.intake)).ok).toBe(true);
  });
});
