/** Builds the plain-text note produced by the dashboard's "Copy summary" button. */
import { getReference, REFERENCE_INVENTORY_VERSION } from "./references";
import type { AnalysisResult, ConcernLevel } from "./schemas";
import { APP_VERSION } from "./version";

export const CONCERN_LABELS: Record<ConcernLevel, string> = {
  elevated_concern: "Elevated concern — reference-listed markers found",
  possible_concern: "Possible concern — some reference-listed markers found",
  no_specific_markers_identified: "No specific markers identified by this prototype",
  insufficient_information: "Insufficient information",
};

export const DEMO_DISCLAIMER =
  "SYNTHETIC DEMO — not clinical software, no real patient data. Supplements clinician judgment; " +
  "does not diagnose, rule out disease, assign ESI, order tests, or route patients. Not validated.";

export function sourceLabel(id: string): string {
  return getReference(id)?.shortName ?? id;
}

export function buildSummaryText(
  data: AnalysisResult,
  opts: { source: "live" | "fixture"; missing: string[] },
): string {
  const lines: string[] = [];
  lines.push("PulseEquity — clinical decision support (synthetic demo)");
  lines.push(opts.source === "fixture" ? "Source: Prewritten demo response — not generated by live Claude." : "Source: Live Claude response.");
  lines.push("");
  lines.push(`Category: ${CONCERN_LABELS[data.concernLevel]}`);
  if (data.concernLevel === "no_specific_markers_identified") {
    lines.push("Note: This does not rule out cardiac disease and does not establish urgency or lack of urgency.");
  }
  lines.push(`Summary: ${data.summary}`);
  lines.push(`Recommended next step: ${data.recommendedAction}`);
  lines.push("");
  lines.push(`Findings (${data.detectedMarkers.length}):`);
  if (data.detectedMarkers.length === 0) lines.push("- None identified against the supplied references.");
  for (const m of data.detectedMarkers) {
    lines.push(`- ${m.marker}: ${m.explanation} [Intake evidence: "${m.inputEvidence.replace(/^["“]+|["”]+$/g, "")}"; Source: ${m.sourceIds.map(sourceLabel).join(", ")}]`);
  }
  if (data.potentialDismissalPattern) {
    lines.push("");
    lines.push(`Possible dismissal pattern (attribution risk, not proven clinician bias): ${data.potentialDismissalPattern}`);
  }
  lines.push("");
  lines.push("Limitations & unknowns:");
  for (const l of data.limitations) lines.push(`- ${l}`);
  if (opts.missing.length) lines.push(`- Not recorded in intake: ${opts.missing.join(", ")}.`);
  lines.push("- Not validated; no clinical accuracy or safety has been demonstrated.");
  lines.push("");
  lines.push(DEMO_DISCLAIMER);
  lines.push(`App version ${APP_VERSION} · Reference inventory ${REFERENCE_INVENTORY_VERSION}`);
  return lines.join("\n");
}
